<?php

use App\Support\TextNormalizer;

// 文字をそろえる（詳細設計書 4.3）

it('文字をそろえる', function (string $input, string $expected) {
    expect(TextNormalizer::normalize($input))->toBe($expected);
})->with([
    '半角カタカナを全角に' => ['ｼﾞｬｶﾞｲﾓ', 'ジャガイモ'],
    '全角英字を半角に' => ['Ｔｏｍａｔｏ', 'Tomato'],
    '全角数字を半角に' => ['大さじ２', '大さじ2'],
    '前後の全角空白を取る' => ['　肉じゃが ', '肉じゃが'],
    '続く空白を1つに' => ['豚肉　 の  炒め物', '豚肉 の 炒め物'],
    'ひらがなはそのまま' => ['にくじゃが', 'にくじゃが'],
    '濁点は1文字にまとめる' => ["か\u{3099}", 'が'],
    '空白だけなら空に' => ['　 ', ''],
]);
